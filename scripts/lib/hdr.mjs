/**
 * Minimal Radiance (.hdr) writer.
 *
 * Emits new-style RLE scanlines — the only variant three's HDRLoader and
 * three-stdlib's RGBELoader (which drei's <Environment> uses) accept
 * without falling back to a flat read.
 *
 * Scanline layout, per the Radiance spec:
 *   [0x02, 0x02, width >> 8, width & 0xff] then four RLE channel streams
 *   (R, G, B, E). In each stream a count byte > 128 means "repeat the next
 *   byte (count - 128) times"; a count <= 128 means "copy the next `count`
 *   bytes verbatim".
 */

const MAX_RUN = 127; // 128 + 127 = 255, the largest count byte
const MAX_LITERAL = 128;

/** Float RGB → shared-exponent RGBE bytes. */
export function floatToRgbe(r, g, b) {
  const peak = Math.max(r, g, b);
  if (peak < 1e-32) return [0, 0, 0, 0];
  const exponent = Math.ceil(Math.log2(peak));
  const scale = Math.pow(2, -exponent) * 256;
  return [
    Math.min(255, Math.max(0, Math.floor(r * scale))),
    Math.min(255, Math.max(0, Math.floor(g * scale))),
    Math.min(255, Math.max(0, Math.floor(b * scale))),
    exponent + 128,
  ];
}

function encodeChannel(data, width, out) {
  let i = 0;
  while (i < width) {
    // How long does the byte at `i` repeat?
    let run = 1;
    while (i + run < width && data[i + run] === data[i] && run < MAX_RUN) run++;

    if (run >= 4) {
      out.push(128 + run, data[i]);
      i += run;
      continue;
    }

    // Otherwise emit a literal block, stopping when a worthwhile run begins.
    const start = i;
    let literal = 0;
    while (i < width && literal < MAX_LITERAL) {
      let ahead = 1;
      while (i + ahead < width && data[i + ahead] === data[i] && ahead < 4) {
        ahead++;
      }
      if (ahead >= 4) break;
      i++;
      literal++;
    }
    out.push(literal);
    for (let k = 0; k < literal; k++) out.push(data[start + k]);
  }
}

/**
 * @param {number} width
 * @param {number} height
 * @param {Float32Array} rgb  width*height*3, linear radiance
 * @returns {Buffer}
 */
export function encodeHdr(width, height, rgb) {
  const header =
    '#?RADIANCE\n' +
    '# Generated by scripts/generate-hdri.mjs — E30 Forge\n' +
    'FORMAT=32-bit_rle_rgbe\n\n' +
    `-Y ${height} +X ${width}\n`;

  const parts = [Buffer.from(header, 'ascii')];
  const channels = [
    new Uint8Array(width),
    new Uint8Array(width),
    new Uint8Array(width),
    new Uint8Array(width),
  ];

  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const i = (y * width + x) * 3;
      const [r, g, b, e] = floatToRgbe(rgb[i], rgb[i + 1], rgb[i + 2]);
      channels[0][x] = r;
      channels[1][x] = g;
      channels[2][x] = b;
      channels[3][x] = e;
    }
    const scanline = [2, 2, (width >> 8) & 0xff, width & 0xff];
    for (const channel of channels) encodeChannel(channel, width, scanline);
    parts.push(Buffer.from(scanline));
  }

  return Buffer.concat(parts);
}
